#!/usr/bin/env python3
"""Render thin native adapters. No dependencies; --check never writes."""
import argparse
import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]


def expected(root=ROOT):
    roles = json.loads((root / 'harness/roles/registry.json').read_text())
    files = {'.codex/config.toml': '[agents]\nenabled = true\nmax_concurrent_threads_per_session = 3\n',
             'CLAUDE.md': '@AGENTS.md\n\nAdapter Claude Code: role w `.claude/agents/`, wspólne skills w `.claude/skills/`.\nPrzeczytaj `harness/workflows/delivery.md` przed delegowaniem zadania.\n'}
    for name, role in roles.items():
        instruction = ('Przeczytaj AGENTS.md, harness/workflows/delivery.md oraz '
                       f'harness/roles/{name}.md i wykonaj zadanie w granicach tej roli. '
                       'Ścieżki odnoszą się do root repozytorium. Nie deleguj dalej. ')
        if name.endswith('reviewer'):
            instruction += ('Nie edytuj ocenianego kodu. W Codex wymagaj osobnej sesji nadrzędnej '
                            'read-only bez mutujących integracji; jeśli jej brak, zwróć BLOCKED '
                            'i skieruj orchestratora do harness/scripts/review.py. ')
        files[f'.codex/agents/{name}.toml'] = (
            '# Generated by harness/scripts/sync.py; edit canonical role/registry.\n'
            f'name = {json.dumps(name)}\n'
            f'description = {json.dumps(role["description"], ensure_ascii=False)}\n'
            f'developer_instructions = {json.dumps(instruction, ensure_ascii=False)}\n'
            + ('\n[features]\napps = false\nplugins = false\nrequest_permissions_tool = false\n'
               if role['access'] == 'read' else ''))
        read = role['access'] == 'read'
        tools = ['Read', 'Grep', 'Glob'] if read else ['Read', 'Grep', 'Glob', 'Edit', 'Write', 'Bash']
        files[f'.claude/agents/{name}.md'] = (
            '---\n' + f'name: {name}\n'
            f'description: {json.dumps(role["description"], ensure_ascii=False)}\n'
            'model: inherit\n'
            f'tools: {json.dumps(tools)}\n'
            'permissionMode: default\n'
            f'skills: {json.dumps(role["skills"])}\n'
            '---\n\n<!-- Generated by harness/scripts/sync.py -->\n' + instruction.rstrip() + '\n')
    links = {}
    for folder in sorted((root / 'harness/skills').iterdir()):
        if (folder / 'SKILL.md').is_file():
            for adapter in ('.agents', '.claude'):
                links[f'{adapter}/skills/{folder.name}'] = f'../../harness/skills/{folder.name}'
    return files, links


def sync(root=ROOT, check=False):
    files, links = expected(root)
    failures = []
    for rel, content in files.items():
        p = root / rel
        if not p.is_symlink() and p.is_file() and p.read_text() == content:
            continue
        failures.append(rel)
        if not check:
            if p.is_symlink():
                raise ValueError('Refusing to overwrite symlink: ' + rel)
            p.parent.mkdir(parents=True, exist_ok=True)
            p.write_text(content)
    for rel, target in links.items():
        p = root / rel
        if p.is_symlink() and os.readlink(p) == target:
            continue
        failures.append(rel)
        if not check:
            if p.exists() or p.is_symlink():
                raise ValueError('Refusing to overwrite existing skill path: ' + rel)
            p.parent.mkdir(parents=True, exist_ok=True)
            p.symlink_to(target, target_is_directory=True)
    return failures


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    drift = sync(check=args.check)
    if args.check and drift:
        raise SystemExit('FAIL adapter drift: ' + ', '.join(drift))
    print('PASS adapter consistency' if args.check else 'Adapters generated')
